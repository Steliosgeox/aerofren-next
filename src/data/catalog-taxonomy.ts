function createSubcategory(
  parentCategorySlug: string,
  parentCategoryNameEl: string,
  slug: string,
  content: {
    focusEl: string;
    contextEl: string;
    selectionEl: string;
    applicationsEl: [string, string, string];
    faqsEl: SeoFaqItem[];
    seoTitle: string;
    seoDescription: string;
  },
): CatalogSubcategory {
  const product = productBySlug[slug];

  if (!product) {
    throw new Error(`Missing product showcase item for slug "${slug}"`);
  }

  return {
    ...product,
    parentCategorySlug,
    canonicalPath: `/products/${parentCategorySlug}/${slug}`,
    descriptionEl: buildSubcategoryDescription(
      product.nameEl,
      parentCategoryNameEl,
      content.focusEl,
      content.contextEl,
      content.selectionEl,
    ),
    applicationsEl: content.applicationsEl,
    faqsEl: content.faqsEl,
    seoTitle: content.seoTitle,
    seoDescription: content.seoDescription,
  };
}


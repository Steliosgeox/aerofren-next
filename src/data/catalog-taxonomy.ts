export function getCategoryBySlug(slug: string) {
  return catalogCategories.find((category) => category.slug === slug);
}

export function getSubcategoryBySlug(slug: string) {
  return catalogCategories
    .flatMap((category) => category.subcategories)
    .find((subcategory) => subcategory.slug === slug);
}

export function getCategoryStaticParams() {
  return catalogCategories.map((category) => ({ category: category.slug }));
}

export function getSubcategoryStaticParams() {
  return catalogCategories.flatMap((category) =>
    category.subcategories.map((subcategory) => ({
      category: category.slug,
      subcategory: subcategory.slug,
    })),
  );
}

